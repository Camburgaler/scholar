/**
 * @interface SlopeIntercept
 * @description An interface representing a slope-intercept line.
 * @member slope - The slope of the line. I.e. the m in y = mx + b
 * @member intercept - The intercept of the line. I.e. the b in y = mx + b
 */
export default interface SlopeIntercept {
    Slope: number;
    Intercept: number;
}
